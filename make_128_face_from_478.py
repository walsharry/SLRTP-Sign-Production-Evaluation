def make_128_face_from_478(face: torch.Tensor):
    # select the keypoints that are needed for the 128 face
    face = face[:, face_478_to_128, ...]
    # order the keypoints
    mapping = tuple(order_128.items())
    # sort mapping by v[0]
    _face = torch.zeros_like(face)
    for a, b in mapping:
        _face[:, b, ...] = face[:, a, ...]
    return _face


